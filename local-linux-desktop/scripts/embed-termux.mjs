import { readFile, writeFile } from 'node:fs/promises';

// Bundle the exact scripts in this project; never fetch executable code at runtime.
const setup = await readFile(new URL('../termux/setup.sh', import.meta.url), 'utf8');
const start = await readFile(new URL('../termux/start.sh', import.meta.url), 'utf8');
await writeFile(new URL('../src/termux-scripts.ts', import.meta.url),
  `// Generated by scripts/embed-termux.mjs. Edit the shell scripts instead.\nexport const SETUP_SCRIPT = ${JSON.stringify(setup)};\nexport const START_SCRIPT = ${JSON.stringify(start)};\n`);
